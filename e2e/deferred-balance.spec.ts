import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const file=process.env.DEFERRED_BALANCE_FIXTURE;
test.skip(!file,'Start API test/deferred-balance.fixture.cjs with disposable local MongoDB; complete coverage runner starts it automatically.');
test.describe.configure({mode:'serial'});
for(const width of [1440,390])test(`deposit is issued alone; actual settlement creates one booked balance at ${width}px`,async({page,request},info)=>{
  const browserErrors:string[]=[];page.on('pageerror',error=>browserErrors.push(error.message));
  const f=JSON.parse(fs.readFileSync(file!,'utf8'));
  expect((await request.post(f.url+'/fixture/deferred-new')).ok()).toBe(true);
  const snapshot=async()=>{const r=await request.get(f.url+'/fixture/edit-snapshot');expect(r.ok()).toBe(true);return r.json();};
  const before=await snapshot(),ids=f.ids;
  await page.setViewportSize({width,height:1000});
  await page.addInitScript(token=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify({role:'admin',email:'synthetic@example.invalid'}));},f.tokens.admin);
  let creates=0;
  await page.route('**/*',async route=>{
    const req=route.request(),u=new URL(req.url());if(!['xhr','fetch'].includes(req.resourceType()))return route.continue();
    if(u.pathname==='/payment-requests'&&req.method()==='POST')creates++;
    if(/^\/(payment-requests|payments|bookings|clients|retreats)(\/|$)/.test(u.pathname))return route.fulfill({response:await route.fetch({url:f.url+u.pathname+u.search})});
    if(req.method()!=='GET')throw Error('Unexpected write '+req.method()+' '+u.pathname);
    const option={key:'shared',legacyRoomType:'shared',labels:{en:'Shared room'},occupancy:'shared',active:true,supported:true,availableUnits:null,unit:'beds'};
    if(u.pathname.startsWith('/room-inventory/payment-accommodation/'))return route.fulfill({json:{options:[option],rooms:[],configured:false,house:null}});
    if(u.pathname==='/room-inventory/options')return route.fulfill({json:[option]});
    if(u.pathname.startsWith('/room-inventory/preference/'))return route.fulfill({json:{key:'shared',label:'Shared room'}});
    if(u.pathname==='/environment/status')return route.fulfill({json:{environment:'local',production:false,enabledJobs:[]}});
    if(u.pathname==='/payment-request-types')return route.fulfill({json:[{key:'deposit',label:'Deposit',active:true,system:true},{key:'balance',label:'Balance',active:true,system:true}]});
    return route.fulfill({json:u.pathname.includes('config-summary')?{}:[]});
  });
  await page.goto(`/admin/payment-requests/new?clientId=${ids.clients[0]}&retreatId=${ids.retreat}&bookingId=${ids.bookings[0]}&requestType=deposit&fullPrice=2500&currency=PLN`);
  const plan=page.getByLabel('Final balance plan');await expect(plan).toBeVisible();
  await expect(plan).toContainText('Only this deposit request is created now');
  await expect(page.getByLabel('Also create the final payment request')).toHaveCount(0);
  await expect(page.getByLabel('Requested Amount *')).toHaveValue('1000');
  await page.getByRole('combobox',{name:/^Accommodation/}).selectOption('shared');
  await page.getByRole('button',{name:'Create Request',exact:true}).click();
  await expect(page).toHaveURL(/\/admin\/payment-requests$/);
  let saved=await snapshot();expect(creates).toBe(1);expect(saved.requests).toHaveLength(before.requests.length+1);
  const deposit=saved.requests.find((r:any)=>!before.requests.some((old:any)=>old._id===r._id));expect(deposit.requestType).toBe('deposit');
  const pay=async(amount:number)=>{
    const response=await request.post(f.url+'/payments',{headers:{Authorization:'Bearer '+f.tokens.admin},data:{clientId:ids.clients[0],retreatId:ids.retreat,bookingId:ids.bookings[0],paymentRequestId:deposit._id,amount,currency:'PLN',paymentDate:'2026-11-19',paymentMethod:'bank_transfer',paymentType:'regular_payment',status:'completed'}});
    expect(response.ok(),await response.text()).toBe(true);
  };
  await pay(400);saved=await snapshot();expect(saved.requests.filter((r:any)=>r.requestType==='balance')).toHaveLength(0);
  await page.goto('/admin/bookings/'+ids.bookings[0]);await page.getByRole('tab',{name:'Payments',exact:true}).click();
  await expect(page.getByText(/The final balance request will be created after the first payment request is fully paid/)).toBeVisible();
  await expect(page.getByRole('button',{name:'Create balance request',exact:true})).toHaveCount(0);
  await pay(600);await page.reload();
  if(await page.getByRole('tab',{name:'Payments',exact:true}).getAttribute('aria-selected')!=='true')await page.getByRole('tab',{name:'Payments',exact:true}).click();
  saved=await snapshot();const balances=saved.requests.filter((r:any)=>r.requestType==='balance');expect(balances).toHaveLength(1);
  expect(balances[0]).toMatchObject({bookingId:ids.bookings[0],requestedAmount:1500,currency:'PLN',dueDate:'2098-12-02T00:00:00.000Z'});
  await expect(page.getByRole('link',{name:'Review existing balance request #'+balances[0].invoiceNumber})).toBeVisible();
  await page.getByLabel('Existing final balance').scrollIntoViewIfNeeded();await page.screenshot({path:info.outputPath(`balance-${width}.png`)});
  expect(saved.payments).toHaveLength(2);expect(saved.emails).toEqual([]);
  expect(saved.requests.find((r:any)=>r._id===ids.requests[1])).toEqual(before.requests.find((r:any)=>r._id===ids.requests[1]));
  expect(browserErrors).toEqual([]);
  await page.unrouteAll({behavior:'wait'});
});
