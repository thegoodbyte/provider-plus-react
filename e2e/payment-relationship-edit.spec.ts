import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const file=process.env.PAYMENT_EDIT_FIXTURE,f=file?JSON.parse(fs.readFileSync(file,'utf8')):{};
test.skip(!file,'Requires disposable real Mongo/Nest payment relationship fixture');
test.describe.configure({mode:'serial'});
for(const width of [1440,390])test(`clear request and correct payment client with reload/recovery at ${width}px`,async({page,request})=>{
 await request.post(f.url+'/fixture/edit-reset');
 const data=await(await request.get(f.url+'/fixture/edit-data')).json();
 const before=await(await request.get(f.url+'/fixture/edit-snapshot')).json();
 await page.setViewportSize({width,height:1000});
 await page.addInitScript(token=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify({id:'staff',role:'admin',email:'staff@example.invalid'}));},f.tokens.admin);
 await page.route('**/*',async route=>{
  const r=route.request(),u=new URL(r.url());if(!['xhr','fetch'].includes(r.resourceType()))return route.continue();
  if(u.pathname.startsWith('/payments'))return route.fulfill({response:await route.fetch({url:f.url+u.pathname+u.search})});
  if(u.pathname==='/clients')return route.fulfill({json:data.clients});
  if(u.pathname==='/retreats')return route.fulfill({json:data.retreats});
  if(u.pathname==='/bookings')return route.fulfill({json:data.bookings});
  if(u.pathname==='/payment-requests')return route.fulfill({json:data.requests});
  if(u.pathname==='/environment/status')return route.fulfill({json:{environment:'local',production:false,enabledJobs:[]}});
  return route.fulfill({json:[]});
 });
 const path='/admin/payments/'+data.ids.payments[0]+'/edit';
 const current=async()=>await(await request.get(f.url+'/payments/'+data.ids.payments[0],{headers:{Authorization:'Bearer '+f.tokens.admin}})).json();
 await page.goto(path);
 await page.getByRole('button',{name:'Clear payment request',exact:true}).click();
 await page.getByRole('button',{name:'Update Payment',exact:true}).click();
 await expect(page).toHaveURL(/\/admin\/payments$/);
 await page.goto(path);
 await expect(page.getByRole('button',{name:'Clear payment request',exact:true})).toHaveCount(0);
 await expect(page.getByLabel('Payment client')).toHaveValue(/Anna/);
 let saved=await current();expect(saved.paymentRequestId).toBeFalsy();expect(saved.amount).toBe(150);expect(saved.usd_amount).toBe(157);expect(saved.bookingId._id).toBe(data.ids.bookings[0]);
 // Client-first narrows the request menu; clearing the client then demonstrates request-first selection.
 await page.getByLabel('Payment client').fill('Ben');
 await page.getByText('Ben Synthetic',{exact:true}).click();
 const requestMenu=page.getByRole('button',{name:'Search invoice number, client, or retreat',exact:true});
 await requestMenu.click();
 await expect(page.getByRole('button',{name:/9441.*Ben Synthetic/})).toBeVisible();
 await expect(page.getByRole('button',{name:/9440.*Anna Synthetic/})).toHaveCount(0);
 await requestMenu.click();
 await page.getByLabel('Payment client').locator('..').getByRole('button').first().click();
 await requestMenu.click();
 await expect(page.getByRole('button',{name:/9440.*Anna Synthetic/})).toBeVisible();
 await page.getByRole('button',{name:/9441.*Ben Synthetic/}).click();
 await expect(page.getByLabel('Payment client')).toHaveValue(/Ben/);
 await expect(page.getByLabel('Payment date')).toHaveValue('2026-10-16');
 await page.getByRole('checkbox',{name:/I confirm correcting this payment/}).check();
 await page.getByLabel('Payment client').scrollIntoViewIfNeeded();
 await page.screenshot({path:`${process.env.PAYMENT_EDIT_ARTIFACT_DIR||'test-results/payment-edit'}/payment-edit-${width}.png`});
 await page.getByRole('button',{name:'Update Payment',exact:true}).click();
 await expect(page).toHaveURL(/\/admin\/payments$/);
 await page.goto(path);await expect(page.getByLabel('Payment client')).toHaveValue(/Ben/);
 saved=await current();expect(saved.clientId._id).toBe(data.ids.clients[1]);expect(saved.paymentRequestId._id).toBe(data.ids.requests[1]);expect(saved.bookingId._id).toBe(data.ids.bookings[1]);expect(saved.amount).toBe(150);expect(saved.paymentMethod).toBe('cash');
 // A late derived-ledger failure is recoverable after a fresh read without resending money.
 await request.post(f.url+'/fixture/fail-next-refresh');
 await page.getByRole('button',{name:'Clear payment request',exact:true}).click();
 await page.getByRole('button',{name:'Update Payment',exact:true}).click();
 await expect(page.getByRole('button',{name:'Finish saved payment edit',exact:true})).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'Finish saved payment edit',exact:true}).click();
 await expect(page).toHaveURL(/\/admin\/payments$/);
 saved=await current();expect(saved.relationshipChangePending).toBeFalsy();expect(saved.paymentRequestId).toBeFalsy();expect(saved.amount).toBe(150);expect(saved.usd_amount).toBe(157);
 const after=await(await request.get(f.url+'/fixture/edit-snapshot')).json();
 expect(after.payments.length).toBe(2);expect(after.payments[1]).toEqual(before.payments[1]);expect(after.bookings[0].amountPaid).toBe(0);expect(after.bookings[1].amountPaid).toBe(350);expect(after.requests[0].amountReceived).toBe(0);expect(after.requests[1].amountReceived).toBe(200);expect(after.emails).toEqual([]);expect(after.receipts).toEqual([]);
});
