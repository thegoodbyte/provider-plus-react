import { test, expect } from '@playwright/test';
import fs from 'node:fs';
const fixturePath = process.env.PPVC922_FIXTURE;
const f = fixturePath ? JSON.parse(fs.readFileSync(fixturePath, 'utf8')) : {};
test.skip(!fixturePath, 'Requires the disposable PPVC-922 Nest/Mongo fixture');
test.describe.configure({ mode: 'serial' });
for (const width of [1440, 390]) test(`dated instructions and approval at ${width}px`, async ({ page, request }) => {
  await request.post(f.url + '/fixture/reset');
  await page.setViewportSize({ width, height: 980 });
  await page.addInitScript(token => { localStorage.setItem('token', token); localStorage.setItem('user', JSON.stringify({ id: 'staff', role: 'medical_staff', email: 'medical_staff@example.invalid' })); }, f.tokens.medical_staff);
  await page.route('**/*', async route => {
    const req = route.request(); if (!['xhr', 'fetch'].includes(req.resourceType())) return route.continue();
    const url = new URL(req.url());
    if (url.pathname.startsWith('/booking-flow') || url.pathname.startsWith('/bookings/')) return route.fulfill({ response: await route.fetch({ url: f.url + url.pathname + url.search }) });
    if (url.pathname === '/environment/status') return route.fulfill({ json: { environment: 'local', production: false, enabledJobs: [] } });
    return route.fulfill({ json: [] });
  });
  const path = `/medical/bookings/${f.booking}/medication-stop-plan?medicalReviewRequestId=${f.review}&artifactId=${f.artifact}`;
  await page.goto(path);
  await expect(page.getByRole('heading', { name: 'Medical Preparation Calendar' })).toBeVisible();
  await page.getByLabel('Medication or substance', { exact: true }).fill('Alcohol');
  await page.getByRole('textbox', { name: 'Instruction shown to client', exact: true }).fill('Remain sober per the medical advisor.');
  await page.getByLabel('Or calendar months before retreat').fill('1');
  await expect(page.getByText('Preparation date: 2026-10-17')).toBeVisible();
  await page.getByRole('button', { name: 'Add calendar item' }).click();
  await page.getByLabel('Medication or substance', { exact: true }).nth(1).fill('Supplements');
  await page.getByRole('textbox', { name: 'Instruction shown to client', exact: true }).nth(1).fill('Stop supplements except magnesium per the medical advisor.');
  await page.getByLabel('Or days before retreat').nth(1).fill('5');
  await expect(page.getByText('Preparation date: 2026-11-12')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Medical approve' })).toBeDisabled();
  await page.getByRole('button', { name: 'Save draft' }).click();
  await expect(page.getByText(/Draft saved/)).toBeVisible();
  const snapshot = await (await request.get(f.url + '/fixture/snapshot')).json();
  expect(snapshot.items).toHaveLength(2);
  expect(snapshot.items.every((item: any) => item.metadata.planLifecycle === 'draft' && item.metadata.medicalReviewRequestId === f.review && item.metadata.artifactId === f.artifact)).toBeTruthy();
  await expect(page.getByRole('button', { name: 'Publish to IR' })).toBeDisabled();
  await page.getByRole('button', { name: 'Medical approve' }).click();
  await expect(page.getByRole('button', { name: 'Publish to IR' })).toBeEnabled();
  await page.getByRole('button', { name: 'Publish to IR' }).click();
  await expect(page.getByText('Status: published')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Or calendar months before retreat').first()).toHaveValue('1');
  await page.getByRole('button', { name: 'Calendar view', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Preparation calendar' })).toContainText('Supplements');
  await page.getByLabel('Calendar month').fill('2026-10');
  await expect(page.getByRole('region', { name: 'Preparation calendar' })).toContainText('Alcohol');
  await page.screenshot({ path: `../ppvc-922-validation/calendar-${width}.png`, fullPage: true });
  await request.post(f.url + '/fixture/reschedule', { data: { startDate: '2026-12-17' } });
  const after = await (await request.get(f.url + '/fixture/snapshot')).json();
  expect(after.items.find((item: any) => item.title === 'Alcohol').dueDate.slice(0,10)).toBe('2026-11-17');
  expect(after.items.find((item: any) => item.title === 'Supplements').dueDate.slice(0,10)).toBe('2026-12-12');
});

test('API rejects unauthorized publication and invalid offsets without partial writes', async ({ request }) => {
  await request.post(f.url + '/fixture/reset');
  const path = f.url + `/booking-flow/bookings/${f.booking}/medication-stop-plan`;
  expect((await request.get(path)).status()).toBe(401);
  expect((await request.get(path, { headers: { Authorization: 'Bearer ' + f.tokens.client } })).status()).toBe(403);
  const headers = { Authorization: 'Bearer ' + f.tokens.medical_staff };
  const entries = [{ name: 'Alcohol', instruction: 'Advisor instruction', monthsBeforeRetreat: 1 }];
  expect((await request.put(path, { headers, data: { entries } })).ok()).toBeTruthy();
  expect((await request.post(path + '/publish', { headers })).status()).toBe(400);
  const before = await (await request.get(f.url + '/fixture/snapshot')).json();
  expect((await request.put(path, { headers, data: { entries: [...entries, { name: 'Supplements', instruction: 'Advisor instruction', daysBeforeRetreat: -1 }] } })).status()).toBe(400);
  expect(await (await request.get(f.url + '/fixture/snapshot')).json()).toEqual(before);
});
