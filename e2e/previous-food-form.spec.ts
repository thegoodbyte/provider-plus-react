import { test, expect } from '@playwright/test';
import fs from 'node:fs';
// Both viewport journeys reset the same disposable booking/form fixture.
test.describe.configure({ mode: 'serial' });
const fixturePath = process.env.PREVIOUS_FOOD_FORM_FIXTURE;
const f = fixturePath ? JSON.parse(fs.readFileSync(fixturePath, 'utf8')) : {};
test.skip(!fixturePath, 'Requires the disposable real Mongo/Nest previous-food-form fixture');
for (const width of [1440, 390]) test(`saved previous food form in table/cards at ${width}px`, async ({ page, request }) => {
  await request.post(f.url + '/fixture/reset');
  const retreat = await (await request.get(f.url + '/fixture/retreat')).json();
  await page.setViewportSize({width,height:1080});
  await page.addInitScript(token => {
    localStorage.setItem('token', token);
    localStorage.setItem('user', JSON.stringify({id:'staff',role:'admin',email:'admin@example.invalid'}));
  }, f.tokens.admin);
  await page.route('**/*', async route => {
    const r = route.request(), u = new URL(r.url());
    if (!['xhr','fetch'].includes(r.resourceType())) return route.continue();
    if (u.pathname.includes('/food-matrix')) return route.fulfill({response:await route.fetch({url:f.url + u.pathname + u.search})});
    if (u.pathname === '/retreats/' + f.ids.retreat) return route.fulfill({json:retreat});
    if (u.pathname === '/retreats') return route.fulfill({json:[retreat]});
    if (u.pathname === '/environment/status') return route.fulfill({json:{environment:'local',production:false,enabledJobs:[]}});
    return route.fulfill({json:[]});
  });
  const path = '/admin/retreats/' + f.ids.retreat + '/foodMatrix';
  await page.goto(path);
  const choice = () => page.getByRole('checkbox',{name:'Use the previous food form for Returning G.'});
  await expect(choice()).toBeVisible();
  await expect(choice()).not.toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toHaveCount(0);
  await choice().click();
  await expect(choice()).toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toBeVisible();
  await expect(page.getByText('Peanuts',{exact:true})).toBeVisible();
  await page.reload();
  await expect(choice()).toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toBeVisible();
  await choice().locator('..').screenshot({path:`${process.env.PREVIOUS_FOOD_FORM_ARTIFACT_DIR || 'test-results/previous-food-form'}/food-checkbox-${width}.png`});
  await page.getByRole('button',{name:'Cards',exact:true}).click();
  await expect(choice()).toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toBeVisible();
  await page.locator('.food-matrix-shell').screenshot({path:`${process.env.PREVIOUS_FOOD_FORM_ARTIFACT_DIR || 'test-results/previous-food-form'}/food-matrix-${width}.png`});
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download PDF'}).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toContain('food-matrix-');
  await download.saveAs(`${process.env.PREVIOUS_FOOD_FORM_ARTIFACT_DIR || 'test-results/previous-food-form'}/food-matrix-${width}.pdf`);
  await expect(page.getByRole('button',{name:'Download PDF'})).toBeEnabled();
  await choice().click();
  await expect(choice()).not.toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toHaveCount(0);
  await page.reload();
  await expect(choice()).not.toBeChecked();
  await expect(page.getByText('Vegetarian',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('checkbox',{name:'Use the previous food form for Sibling G.'})).not.toBeChecked();
  await expect(page.getByText('Current diet',{exact:true})).toBeVisible();
});
