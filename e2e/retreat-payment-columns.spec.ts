import {test,expect} from '@playwright/test';
for(const width of [1440,390])test(`retreat payment columns keep ledger balances and currencies at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:1000});const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const client={_id:'c1',firstName:'Synthetic',lastName:'Guest',display_id:1900,email:'fixture@example.invalid'};
 const bookings=[{_id:'b1',clientId:client,retreatId:'r1',status:'confirmed',currency:'EUR',totalAmount:1000,amountPaid:400},{_id:'b2',clientId:client,retreatId:'r1',status:'confirmed',currency:'PLN',totalAmount:850,amountPaid:0}];
 const payment={_id:'p1',clientId:client,bookingId:'b1',retreatId:'r1',amount:400,currency:'EUR',status:'completed',paymentMethod:'bank_transfer',isDeposit:true,description:'Synthetic deposit',paymentDate:'2026-10-20'};
 const retreat={_id:'r1',name:'Synthetic Retreat',code:'SYN900',type:'regular',status:'scheduled',startDate:'2099-01-01',endDate:'2099-01-07',capacity:20};
 await page.route('**/*',async route=>{const r=route.request();if(!['xhr','fetch'].includes(r.resourceType()))return route.continue();const p=new URL(r.url()).pathname;
  if(r.method()!=='GET')throw Error('Unexpected production mutation '+p);
  if(p==='/environment/status')return route.fulfill({json:{environment:'local',production:false,enabledJobs:[]}});
  if(p.startsWith('/payments/retreat-summary/'))return route.fulfill({json:{totalPayments:400,totalPaymentsEUR:400,completedPayments:400,completedPaymentsEUR:400,completedPaymentsUSD:400,pendingPayments:0,paymentsByMethod:{},paymentsByStatus:{},depositsPaid:400,finalPaymentsPaid:0}});
  if(p.startsWith('/payments/by-retreat/'))return route.fulfill({json:[payment]});
  if(p.startsWith('/bookings/retreat/'))return route.fulfill({json:bookings});
  if(p==='/retreats/r1')return route.fulfill({json:retreat});
  if(p==='/retreats')return route.fulfill({json:[retreat]});
  if(p==='/clients')return route.fulfill({json:[client]});
  return route.fulfill({json:[]});
 });
 await page.goto('/admin/retreats/r1/payments');
 await expect(page.getByRole('button',{name:'List',exact:true})).toHaveClass(/is-active/);
 await page.getByRole('button',{name:'Columns',exact:true}).click();
 const column=page.locator('.payment-column');await expect(column).toHaveCount(1);
 await expect(column.getByText('Agreed: 1,000 EUR',{exact:true})).toBeVisible();
 await expect(column.getByText('Agreed: 850 PLN',{exact:true})).toBeVisible();
 await expect(column.getByText('600 EUR',{exact:true})).toBeVisible();
 await expect(column.getByText('850 PLN',{exact:true})).toBeVisible();
 await expect(column.getByText('Synthetic deposit',{exact:true})).toBeVisible();
 await expect(column.getByRole('link',{name:'#1900'})).toHaveAttribute('href','/admin/clients/c1');
 await page.screenshot({path:`../payment-columns-${width}.png`,fullPage:true});
 await page.getByRole('button',{name:'List',exact:true}).click();await expect(page.getByText('Transaction ID',{exact:true})).toBeVisible();expect(errors).toEqual([]);
});
