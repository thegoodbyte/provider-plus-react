import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const file=process.env.GBP_CURRENCY_FIXTURE;
test.skip(!file,'Requires the real GBP API/Mongo fixture; full coverage starts it automatically.');
test.describe.configure({mode:'serial'});
for(const width of [1440,390]) test(`GBP receipt, payment, booking balance and portal retain pounds at ${width}px`,async({page,request},info)=>{
 const f=JSON.parse(fs.readFileSync(file!,'utf8'));
 const reset=await request.post(f.url+'/fixture/gbp-reset');expect(reset.ok()).toBe(true);const {ids}=await reset.json();
 const snapshot=async()=>(await request.get(f.url+'/fixture/edit-snapshot')).json();
 const before=await snapshot(),errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width,height:1000});
 await page.addInitScript(token=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify({role:'admin',email:'synthetic@example.invalid'}));},f.tokens.admin);
 await page.route('**/*',async route=>{
  const q=route.request(),u=new URL(q.url());if(!['xhr','fetch'].includes(q.resourceType()))return route.continue();
  if(u.pathname.replace(/^\/api/,'')==='/client-portal/account')return route.fulfill({response:await route.fetch({url:f.url+'/fixture/gbp-portal'})});
  if(/^\/(payment-scratchpad|payment-requests|payments|bookings|clients|retreats)(\/|$)/.test(u.pathname))return route.fulfill({response:await route.fetch({url:f.url+u.pathname+u.search})});
  if(q.method()!=='GET')throw Error('Unexpected write '+u.pathname);
  const option={key:'shared',legacyRoomType:'shared',labels:{en:'Shared room'},occupancy:'shared',active:true,supported:true,availableUnits:null,unit:'beds'};
  if(u.pathname.startsWith('/room-inventory/payment-accommodation/'))return route.fulfill({json:{options:[option],rooms:[],configured:false,house:null}});
  if(u.pathname==='/room-inventory/options')return route.fulfill({json:[option]});
  if(u.pathname.startsWith('/room-inventory/preference/'))return route.fulfill({json:{key:'shared',label:'Shared room'}});
  if(u.pathname==='/environment/status')return route.fulfill({json:{environment:'local',production:false,enabledJobs:[]}});
  return route.fulfill({json:u.pathname.includes('config-summary')?{}:[]});
 });
 const capture=async(amount:string)=>{
  await page.goto('/admin/payments/scratchpad/new');
  await page.getByLabel('Amount received',{exact:true}).fill(amount);
  await page.getByLabel('Currency',{exact:true}).selectOption('GBP');
  await page.getByLabel('Payer name (optional)').fill('Synthetic GBP payer');
  await page.getByLabel('Payment request number (optional)').fill('3100');
  await page.getByRole('button',{name:'Save receipt',exact:true}).click();
  await expect(page).toHaveURL(/scratchpad\/[a-f\d]{24}/);
  const id=page.url().match(/scratchpad\/([a-f\d]{24})/)![1];
  await page.reload();
  await expect(page.getByRole('region',{name:'Receipt details'})).toContainText('GBP');
  await page.getByRole('button',{name:'Record payment from SP',exact:true}).click();
  const panel=page.getByRole('region',{name:'Guided scratchpad matching'});
  await expect(panel).toBeVisible();
  await panel.getByRole('checkbox',{name:'Select PR #3100',exact:true}).check();
  await expect(panel).toContainText('GBP');
  await panel.screenshot({path:info.outputPath(`gbp-match-${amount}-${width}.png`)});
  await panel.getByRole('button',{name:'Confirm payment from scratchpad',exact:true}).click();
  await expect(page.getByRole('link',{name:/^View payment #/})).toBeVisible();
  const row=(await request.get(f.url+'/payment-scratchpad/'+id,{headers:{Authorization:'Bearer '+f.tokens.admin}}));expect(row.ok()).toBe(true);expect((await row.json()).currency).toBe('GBP');
  return id;
 };
 await capture('400.25');let saved=await snapshot();expect(saved.payments).toHaveLength(1);expect(saved.requests.filter((r:any)=>r.requestType==='balance')).toHaveLength(0);
 await page.goto('/admin/payments/'+saved.payments[0]._id+'/edit');
 await expect(page.getByRole('combobox',{name:'Currency',exact:true})).toHaveValue('GBP');
 await capture('599.75');saved=await snapshot();
 const balance=saved.requests.find((r:any)=>r.requestType==='balance');expect(balance).toMatchObject({currency:'GBP',bookingId:ids.bookings[0],requestedAmount:1500,usd_amount:2250});
 expect(saved.payments).toHaveLength(2);expect(saved.payments.map((p:any)=>p.currency)).toEqual(['GBP','GBP']);
 expect(saved.bookings.find((b:any)=>b._id===ids.bookings[0]).amountPaid).toBe(1000);
 expect(saved.requests.find((r:any)=>r._id===ids.requests[1])).toEqual(before.requests.find((r:any)=>r._id===ids.requests[1]));
 expect(saved.emails).toEqual([]);
 await page.goto('/admin/bookings/'+ids.bookings[0]);await page.getByRole('tab',{name:'Payments',exact:true}).click();
 await expect(page.getByRole('link',{name:'Review existing balance request #'+balance.invoiceNumber})).toBeVisible();
 await page.getByLabel('Existing final balance').scrollIntoViewIfNeeded();await page.screenshot({path:info.outputPath(`gbp-booking-${width}.png`)});
 const portal=process.env.GBP_IR_URL||process.env.CLIENT_PORTAL_FIXTURE_BASE_URL;expect(portal).toBeTruthy();
 await page.addInitScript(({token,clientId})=>{localStorage.setItem('client_auth_token',token);localStorage.setItem('auth-storage',JSON.stringify({state:{token,isAuthenticated:true,user:{id:clientId,language:'en'}},version:0}));},{token:f.tokens.user,clientId:ids.clients[0]});
 await page.goto(portal+'/payment/'+balance.publicHash);
 await expect(page.getByRole('link',{name:'Pay with PayPal',exact:true})).toHaveAttribute('href','https://www.paypal.com/paypalme/thegoodbyte/2250USD');
 await expect(page.getByText('£1,500.00',{exact:true})).toBeVisible();
 await expect(page.getByTitle('SEPA bank transfer QR code')).toHaveCount(0);
 await page.screenshot({path:info.outputPath(`gbp-portal-${width}.png`),fullPage:true});
 expect((await snapshot()).payments).toEqual(saved.payments);expect(errors).toEqual([]);
});
test.afterEach(async({page})=>{await page.unrouteAll({behavior:'wait'})});
